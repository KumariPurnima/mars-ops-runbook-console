import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

function read(rel) {
  return readFileSync(join(root, rel), 'utf8');
}

const out = `/* generated by scripts/gen-manifests.mjs — do not edit */
export const triageManifest = ${JSON.stringify(read('agents/triage.yaml'))};
export const runbookManifest = ${JSON.stringify(read('agents/runbook.yaml'))};
export const triagePrompt = ${JSON.stringify(read('prompts/triage.tmpl'))};
export const runbookPrompt = ${JSON.stringify(read('prompts/runbook.tmpl'))};
export const triageSkill = {
  name: 'incident-triage',
  description: 'Correlate pager, metrics, logs, and deploys into a working diagnosis.',
  body: ${JSON.stringify(read('agents/skills/incident-triage.md'))},
};
export const runbookSkill = {
  name: 'incident-runbook',
  description: 'Produce gated mitigations, status notes, and a postmortem skeleton.',
  body: ${JSON.stringify(read('agents/skills/incident-runbook.md'))},
};
`;

mkdirSync(join(root, 'lib'), { recursive: true });
writeFileSync(join(root, 'lib/manifests.generated.ts'), out);
console.log('wrote lib/manifests.generated.ts');
